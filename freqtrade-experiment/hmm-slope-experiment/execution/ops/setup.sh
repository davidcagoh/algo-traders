#!/usr/bin/env bash
# Track B one-shot bootstrap.
# Run from execution/ops/ on the VPS. Prompts only for the three values you cannot
# automate (Telegram token+chat_id, healthchecks.io ping URL). Generates the
# REST API password and JWT secret locally with openssl, writes .env and
# config.private.json from templates, builds the image, starts compose,
# tails the log until "Bot heartbeat", then prints next steps.

set -euo pipefail

OPS_DIR="$(cd "$(dirname "$0")" && pwd)"
HARNESS_DIR="${OPS_DIR}/.."
ENV_FILE="${OPS_DIR}/.env"
PRIV_FILE="${HARNESS_DIR}/config.private.json"
PRIV_TEMPLATE="${HARNESS_DIR}/config.private.example.json"

red() { printf "\033[31m%s\033[0m\n" "$*"; }
green() { printf "\033[32m%s\033[0m\n" "$*"; }
bold() { printf "\033[1m%s\033[0m\n" "$*"; }

need() { command -v "$1" >/dev/null || { red "missing: $1"; exit 1; }; }
need docker
need openssl
need curl

if ! docker compose version >/dev/null 2>&1; then
  red "docker compose plugin missing (need 'docker compose', not 'docker-compose')"
  exit 1
fi

if [[ -f "${ENV_FILE}" || -f "${PRIV_FILE}" ]]; then
  red "Refusing to overwrite existing secrets:"
  [[ -f "${ENV_FILE}" ]] && echo "  - ${ENV_FILE}"
  [[ -f "${PRIV_FILE}" ]] && echo "  - ${PRIV_FILE}"
  echo "Delete them first if you really want to re-bootstrap (and restart the 30d clock)."
  exit 1
fi

bold "Track B bootstrap"
echo "Three values you must supply (set them up first if not already):"
echo "  1. Telegram bot token (from @BotFather)"
echo "  2. Telegram chat_id (from https://api.telegram.org/bot<TOKEN>/getUpdates)"
echo "  3. healthchecks.io ping URL (Cron-style check, period 5m, grace 5m)"
echo

read -r -p "Telegram bot token: " TG_TOKEN
read -r -p "Telegram chat_id:   " TG_CHAT
read -r -p "healthchecks.io URL: " HC_URL

[[ -z "${TG_TOKEN}" || -z "${TG_CHAT}" || -z "${HC_URL}" ]] && { red "all three required"; exit 1; }

API_PASSWORD="$(openssl rand -hex 16)"
JWT_SECRET="$(openssl rand -hex 32)"

green "Writing ${ENV_FILE}"
cat >"${ENV_FILE}" <<EOF
# Generated by execution/ops/setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
FT_TELEGRAM_ENABLED=true
FT_TELEGRAM_TOKEN=${TG_TOKEN}
FT_TELEGRAM_CHAT_ID=${TG_CHAT}
FT_API_USERNAME=freqtrade
FT_API_PASSWORD=${API_PASSWORD}
HEALTHCHECK_URL=${HC_URL}
EOF
chmod 600 "${ENV_FILE}"

green "Writing ${PRIV_FILE}"
sed \
  -e "s|REPLACE_WITH_FT_TELEGRAM_TOKEN|${TG_TOKEN}|" \
  -e "s|REPLACE_WITH_FT_TELEGRAM_CHAT_ID|${TG_CHAT}|" \
  -e "s|REPLACE_WITH_FT_API_USERNAME|freqtrade|" \
  -e "s|REPLACE_WITH_FT_API_PASSWORD|${API_PASSWORD}|" \
  -e "s|GENERATE_WITH_openssl_rand_-hex_32|${JWT_SECRET}|" \
  "${PRIV_TEMPLATE}" >"${PRIV_FILE}"
# 644 (not 600) so the non-root ftuser inside the Freqtrade container can
# read the bind-mounted file. /root/ already blocks non-root host users, and
# the file is gitignored, so 644 doesn't widen real exposure.
chmod 644 "${PRIV_FILE}"

# Freqtrade runs as ftuser (UID 1000) inside the container. The bind-mounted
# user_data tree must be writable by that UID for logs/, sqlite, and the
# OHLCV cache to land.
green "chown ${HARNESS_DIR} → 1000:1000 (ftuser inside container)"
chown -R 1000:1000 "${HARNESS_DIR}"

bold "Building image (first run is slow; subsequent runs are cached)"
cd "${OPS_DIR}"
docker compose --env-file .env build

bold "Starting compose"
docker compose --env-file .env up -d

bold "Waiting for 'Bot heartbeat' (up to 5 minutes)"
deadline=$(( $(date +%s) + 300 ))
while (( $(date +%s) < deadline )); do
  if docker compose --env-file .env logs freqtrade 2>/dev/null | grep -q "Bot heartbeat"; then
    green "Bot heartbeat received."
    break
  fi
  sleep 5
done

if ! docker compose --env-file .env logs freqtrade 2>/dev/null | grep -q "Bot heartbeat"; then
  red "No heartbeat in 5 minutes. Check: docker compose logs freqtrade"
  exit 1
fi

bold "Status"
docker compose --env-file .env ps

echo
green "Bootstrap complete."
echo
echo "Next:"
echo "  1. Confirm Telegram received the *startup* message."
echo "  2. Confirm healthchecks.io shows green within ~10 minutes."
echo "  3. From repo root, run: ./freqtrade-experiment/hmm-slope-experiment/execution/ops/snapshot.sh > \\"
echo "       freqtrade-experiment/hmm-slope-experiment/execution/records/results/\$(date -u +%Y-%m-%d)-hl-paper-start.md"
echo "     That records start timestamp + funding rates + regime — the 30d clock starts at the timestamp in that file."
